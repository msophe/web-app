/**
 * Returns a label lookup for the given language code (for example "en-US" or "sw-SW").
 * Unknown keys fall back to English, then to the key itself.
 */
export function statementLabels(languageCode: string): (key: string) => string {
  const table = (languageCode || '').toLowerCase().startsWith('sw') ? SW : EN;
  return (key: string) => table[key] ?? EN[key] ?? key;
}
